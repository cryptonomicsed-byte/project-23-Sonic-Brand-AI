/**
 * Get all providers for a category
 */
export function getProvidersByCategory(category: 'llm' | 'image' | 'video' | 'voice'): ProviderConfig[] {
  let providers: Record<string, ProviderConfig> = {};
  
  switch (category) {
    case 'llm':
      providers = LLM_PROVIDERS;
      break;
    case 'image':
      providers = IMAGE_PROVIDERS;
      break;
    case 'video':
      providers = VIDEO_PROVIDERS;
      break;
    case 'voice':
      providers = VOICE_PROVIDERS;
      break;
  }
  
  return Object.values(providers).sort((a, b) => {
    // Sort by tier (free < pro < enterprise) then by name
    const tierOrder = { free: 0, pro: 1, enterprise: 2, beta: 3 };
    const tierDiff = (tierOrder[a.tier] || 99) - (tierOrder[b.tier] || 99);
    return tierDiff !== 0 ? tierDiff : a.name.localeCompare(b.name);
  });
}

/**
 * Get provider config by ID
 */
export function getProviderConfig(provider: string, category: 'llm' | 'image' | 'video' | 'voice'): ProviderConfig | null {
  const providers = getProvidersByCategory(category);
  return providers.find(p => p.id === provider) || null;
}
